// Rebuild after changing the featured images: node scripts/build-home-textures.cjs
const fs = require('node:fs/promises');
const path = require('node:path');
const vm = require('node:vm');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');

async function build() {
  const context = { window: {} };
  vm.runInNewContext(await fs.readFile(path.join(root, 'assets/js/featured-destinations.js'), 'utf8'), context);
  const textures = {};
  for (const scene of context.window.TripMateFeatured) {
    const image = await sharp(path.join(root, scene.image))
      .resize({ width: 1600, height: 1600, fit: 'inside', withoutEnlargement: true })
      .jpeg({ quality: 90 })
      .toBuffer();
    textures[scene.image] = 'data:image/jpeg;base64,' + image.toString('base64');
  }
  await fs.writeFile(path.join(root, 'assets/js/texture-assets.js'),
    '// Generated by scripts/build-home-textures.cjs; loaded only for file:// previews.\n' +
    'window.TRIPMATE_TEXTURES=' + JSON.stringify(textures) + ';\n');
  console.log('Built offline WebGL textures for ' + Object.keys(textures).length + ' featured images.');
}
build().catch(error => { console.error(error); process.exitCode = 1; });
